<?php
declare(strict_types = 1);

namespace AklebeLaravel\MercyPhpDeployment;

use Symfony\Component\Filesystem\Filesystem;

/**
 * Libraries from a branch or a folder instead of their release: in the dev environment by "git.branches.<repo>"
 * or "git.library_paths.<repo>" (usually in project/config/local.yaml), in the build by "build_steps.branch".
 *
 * A library is every git repository in the "repositories" of the scaffold's composer.json (e.g. mercy-php-deployment),
 * the repo name is the last part of its url. Modules and themes are no libraries, they come from "requires".
 *
 * Composer takes a library by its version (e.g. ^2.1), a branch would not match. So the branch is cloned into
 * CLONE_DIR/<repo> and offered by a path repository with a fixed version of the same major (2.99.0) in
 * composer.local.json, which the merge plugin of the scaffold reads (its repositories come first). Without test
 * branches the file is removed again and composer goes back to the versions of composer.json.
 *
 * Instead of a branch a library can come from a folder of this machine ("git.library_paths.<repo>", e.g. your own
 * working copy in its own PhpStorm project, whatever branch it has): copied into CLONE_DIR/<repo> on every
 * "./mercy update" or "./mercy library:sync" (the container sees only the scaffold, a path outside would not exist there).
 *
 * Composer changes composer.lock meanwhile: do not commit it while a test branch is active.
 */
final class LibraryBranch
{
    public const string LOCAL_COMPOSER = 'composer.local.json';
    public const string CLONE_DIR = 'storage/app/library-branch';

    /**
     * Marks the file as ours: a composer.local.json written by a developer is never touched.
     */
    private const string MARKER = 'Generated by ./mercy';

    public function __construct(private readonly Process $process)
    {
    }

    /**
     * The test branch of a repo: git.branches.<repo> (must exist), otherwise (only with $common) git.branch
     * (used where it exists).
     *
     * @param  Process  $process
     * @param  string   $repo    repo name, e.g. "mercy-php-deployment"
     * @param  bool     $common  also git.branch: the build branch; in the dev environment git.branch is for
     *                           modules and themes only (a library branch changes composer.lock, so only on request)
     *
     * @return array{0: string, 1: bool}|null branch and whether it was set for this repo explicitly
     */
    public static function wanted(Process $process, string $repo, bool $common = false): ?array
    {
        $branches = (array) ($process->getConfigValue('setup.git.branches', []) ?? []);
        if (is_string($branches[$repo] ?? null) && $branches[$repo] !== '') {
            return [$branches[$repo], true];
        }
        if (!$common) {
            return null;
        }
        $branch = $process->getConfigValue('setup.git.branch');

        return is_string($branch) && $branch !== '' ? [$branch, false] : null;
    }

    /**
     * Applies the test branches of all libraries (or removes them again).
     *
     * @param  string  $rootDir         the scaffold
     * @param  bool    $composerUpdate  false if a full "composer update" follows anyway (install)
     * @param  bool    $build           the build: copied into vendor (an image needs the files), git.branch included
     *
     * @return bool
     */
    public function sync(string $rootDir, bool $composerUpdate = true, bool $build = false): bool
    {
        $file = "$rootDir/".self::LOCAL_COMPOSER;
        $current = is_file($file) ? (string) file_get_contents($file) : null;
        if ($current !== null && !str_contains($current, self::MARKER)) {
            if ($this->process->testBranches()) {
                $this->process->warning(self::LOCAL_COMPOSER.' was not written by Mercy, test branches of the libraries are not applied.');
            }

            return true;
        }
        // packages of the last run: they go back to their version when their branch is gone
        $before = (array) (json_decode((string) $current, true)['_mercy']['packages'] ?? []);

        $repositories = $packages = [];
        $paths = (array) ($this->process->getConfigValue('setup.git.library_paths', []) ?? []);
        foreach ($this->libraries($rootDir) as $repo => $url) {
            // a folder of this machine wins over a branch
            if (is_string($paths[$repo] ?? null) && $paths[$repo] !== '') {
                $dir = $paths[$repo];
                $absolute = str_starts_with($dir, '/') ? $dir : "$rootDir/$dir";
                if (($package = $this->packageName($absolute)) === null || ($version = $this->version($rootDir, $absolute, $package)) === null) {
                    $this->process->error("$repo: no composer.json with name and version in '$dir' (git.library_paths.$repo).");

                    return false;
                }
                // copied into the scaffold: the container (composer update of "mercy:app update") sees only the scaffold
                $copy = self::CLONE_DIR."/$repo";
                $this->mirror($absolute, "$rootDir/$copy");
                $repositories[] = ['type' => 'path', 'url' => $copy, 'options' => ['symlink' => !$build, 'versions' => [$package => $version]]];
                $packages[] = $package;
                $this->process->notice(sprintf("%s: from '%s' (%s as %s), copied on every ./mercy update or ./mercy library:sync.", $repo, $dir, $package, $version));
                continue;
            }
            if (($wanted = self::wanted($this->process, $repo, $build)) === null) {
                continue;
            }
            [$branch, $explicit] = $wanted;
            if (!$this->remoteHasBranch($url, $branch)) {
                if ($explicit) {
                    $this->process->error(sprintf("Branch '%s' of %s does not exist (git.branches.%s): %s", $branch, $repo, $repo, $url));

                    return false;
                }
                continue;
            }
            $dir = self::CLONE_DIR."/$repo";
            if (!$this->checkout("$rootDir/$dir", $url, $branch, $rootDir)) {
                return false;
            }
            $package = $this->packageName("$rootDir/$dir");
            if ($package === null || ($version = $this->version($rootDir, "$rootDir/$dir", $package)) === null) {
                $this->process->warning("$repo: no package name or version found in its composer.json, the test branch is not applied.");
                continue;
            }
            $repositories[] = [
                'type'    => 'path',
                'url'     => $dir,
                // fixed version of the same major: matches ^x.y of the scaffold and the modules, a branch name would not
                'options' => ['symlink' => !$build, 'versions' => [$package => $version]],
            ];
            $packages[] = $package;
            $this->process->notice(sprintf("%s: test branch '%s' (%s as %s).", $repo, $branch, $package, $version));
        }

        if ($repositories) {
            $content = json_encode([
                    '_comment'     => self::MARKER.' from git.branch(es)/git.library_paths (project/config/local.yaml), removed again without them. Do not edit, do not commit composer.lock meanwhile.',
                    '_mercy'       => ['packages' => $packages],
                    'repositories' => $repositories,
                ], JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES)."\n";
            if ($content !== $current) {
                file_put_contents($file, $content);
            }
        } elseif ($current !== null) {
            unlink($file);
            $this->process->notice('Test branches of the libraries removed, back to the versions of composer.json.');
        }

        // also when nothing changed: a branch may have new commits
        $update = array_values(array_unique([...$before, ...$packages]));

        if (!$composerUpdate || !$update) {
            return true;
        }

        // --no-scripts: the scripts run with the composer install that follows
        return $this->process->run(['composer', 'update', ...$update, '--no-scripts', '--working-dir='.$rootDir], $rootDir, 600.0);
    }

    /**
     * Git repositories of composer.json: repo name => url.
     *
     * @return array<string, string>
     */
    private function libraries(string $rootDir): array
    {
        $composer = json_decode((string) @file_get_contents("$rootDir/composer.json"), true);
        $libraries = [];
        foreach ((array) ($composer['repositories'] ?? []) as $repository) {
            if (in_array($repository['type'] ?? '', ['vcs', 'git'], true) && ($url = (string) ($repository['url'] ?? '')) !== '') {
                $libraries[basename(rtrim($url, '/'), '.git')] = $url;
            }
        }

        return $libraries;
    }

    private function remoteHasBranch(string $url, string $branch): bool
    {
        return trim((string) $this->process->capture(['git', 'ls-remote', '--heads', $url, "refs/heads/$branch"], null, 30.0)) !== '';
    }

    /**
     * Clone of the branch (a copy of our own, local changes in it are discarded).
     */
    private function checkout(string $dir, string $url, string $branch, string $rootDir): bool
    {
        if (!is_dir("$dir/.git")) {
            // e.g. a copy of git.library_paths before
            new Filesystem()->remove($dir);
            @mkdir(dirname($dir), 0755, true);

            return $this->process->run(['git', 'clone', '--quiet', '--branch', $branch, $url, $dir], $rootDir, 600.0);
        }

        return $this->process->run(['git', 'remote', 'set-url', 'origin', $url], $dir)
               && $this->process->run(['git', 'fetch', '--quiet', 'origin', $branch], $dir, 600.0)
               && $this->process->run(['git', 'checkout', '--quiet', '--force', '-B', $branch, 'FETCH_HEAD'], $dir);
    }

    /**
     * Copy of a library folder (without .git, vendor and node_modules), removed files are removed in the copy too.
     */
    private function mirror(string $source, string $target): void
    {
        $skip = ['.git', 'vendor', 'node_modules'];
        $files = new \RecursiveIteratorIterator(new \RecursiveCallbackFilterIterator(new \RecursiveDirectoryIterator($source, \FilesystemIterator::SKIP_DOTS), fn(\SplFileInfo $file) => !in_array($file->getFilename(), $skip, true),),
            \RecursiveIteratorIterator::SELF_FIRST);
        // fresh copy: mirror() with an own iterator would not delete removed files
        $filesystem = new Filesystem();
        $filesystem->remove($target);
        $filesystem->mirror($source, $target, $files);
    }

    private function packageName(string $dir): ?string
    {
        $name = json_decode((string) @file_get_contents("$dir/composer.json"), true)['name'] ?? null;

        return is_string($name) && $name !== '' ? $name : null;
    }

    /**
     * "<major>.99.0": the major of the scaffold's constraint (e.g. ^2.1), otherwise of the branch alias of the library
     * ("dev-master": "2.x-dev"). Null if neither has one (e.g. a constraint "dev-master").
     */
    private function version(string $rootDir, string $dir, string $package): ?string
    {
        $root = json_decode((string) @file_get_contents("$rootDir/composer.json"), true);
        $library = json_decode((string) @file_get_contents("$dir/composer.json"), true);
        foreach ([(string) ($root['require'][$package] ?? ''), (string) ($library['extra']['branch-alias']['dev-master'] ?? '')] as $source) {
            if (preg_match('/^[\^~>=v\s]*(\d+)\./', $source, $m)) {
                return $m[1].'.99.0';
            }
        }

        return null;
    }
}
